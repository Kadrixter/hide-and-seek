using System;
using UnityEngine;

namespace HideAndSeek.Player
{
    /// <summary>Footstep gait used to pick clip sets and loudness.</summary>
    public enum FootstepGait
    {
        Crouch = 0,
        Walk = 1,
        Run = 2,
    }

    /// <summary>Clip sets for one surface type.</summary>
    [Serializable]
    public class SurfaceClipSet
    {
        public SurfaceType surface;
        public AudioClip[] walk = Array.Empty<AudioClip>();
        public AudioClip[] run = Array.Empty<AudioClip>();
        public AudioClip[] crouch = Array.Empty<AudioClip>();

        public AudioClip[] Get(FootstepGait gait) => gait == FootstepGait.Run ? run : gait == FootstepGait.Crouch ? crouch : walk;
    }

    /// <summary>All movement sounds (generated by the Player audio builder).</summary>
    [CreateAssetMenu(menuName = "HideAndSeek/Player/Footstep Library", fileName = "FootstepLibrary")]
    public class FootstepLibrary : ScriptableObject
    {
        public SurfaceClipSet[] surfaces = Array.Empty<SurfaceClipSet>();
        public AudioClip[] jump = Array.Empty<AudioClip>();
        public AudioClip[] landLight = Array.Empty<AudioClip>();
        public AudioClip[] landHeavy = Array.Empty<AudioClip>();
        public AudioClip[] crouchDown = Array.Empty<AudioClip>();
        public AudioClip[] standUp = Array.Empty<AudioClip>();
        [Tooltip("Seamless loop of clothing rustle, faded in with movement speed.")]
        public AudioClip clothLoop;

        /// <summary>Clip set for a surface, falling back to concrete (or the first set).</summary>
        public SurfaceClipSet GetSurface(SurfaceType type)
        {
            SurfaceClipSet fallback = null;
            for (int i = 0; i < surfaces.Length; i++)
            {
                var s = surfaces[i];
                if (s == null) continue;
                if (s.surface == type) return s;
                if (fallback == null || s.surface == SurfaceType.Concrete) fallback = s;
            }
            return fallback;
        }
    }
}
