using System;
using System.IO;
using HideAndSeek.Core;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;

namespace HideAndSeek.Game.Editor
{
    /// <summary>Assembles the playable beta scene from the Map, Player and Characters modules.</summary>
    public static class BetaSceneBuilder
    {
        private const string MapScene = "Assets/_Project/Map/Scenes/ParkingGarage.unity";
        private const string ShowcaseScene = "Assets/_Project/Characters/Scenes/CharacterShowcase.unity";
        private const string PlayerTestScene = "Assets/_Project/Player/Scenes/PlayerTestRange.unity";
        private const string PlayerPrefab = "Assets/_Project/Player/Prefabs/Player.prefab";
        private const string BetaScene = "Assets/_Project/Game/Scenes/Beta_ParkingGarage.unity";

        public const string LocalBodyLayerName = "LocalPlayerBody";
        public const int LocalBodyLayer = 8;
        private const string BuildOutput = "Builds/Windows/HideAndSeek.exe";

        // Module assets (map, skins, player prefab) are generated by each module's own
        // HideAndSeek/<Module> menu and committed; this only assembles the beta scene.
        [MenuItem("HideAndSeek/Build Beta Scene")]
        public static void BuildBetaSceneMenu() => BuildBetaScene();

        /// <summary>Batch-mode entry: assembles the beta scene.</summary>
        public static void BuildFromCommandLine() => RunBatch(BuildBetaScene);

        /// <summary>Batch-mode entry: assembles the beta scene and builds a Windows player.</summary>
        public static void BuildPlayerFromCommandLine() => RunBatch(() =>
        {
            BuildBetaScene();
            var report = BuildPipeline.BuildPlayer(new BuildPlayerOptions
            {
                scenes = new[] { BetaScene, ShowcaseScene },
                locationPathName = BuildOutput,
                target = BuildTarget.StandaloneWindows64,
                options = BuildOptions.None
            });
            if (report.summary.result != UnityEditor.Build.Reporting.BuildResult.Succeeded)
                throw new Exception($"Player build failed: {report.summary.result}, {report.summary.totalErrors} errors");
            Debug.Log($"[BetaSceneBuilder] Player built to {BuildOutput}");
        });

        private static void RunBatch(Action action)
        {
            try
            {
                action();
                EditorApplication.Exit(0);
            }
            catch (Exception e)
            {
                Debug.LogException(e);
                EditorApplication.Exit(1);
            }
        }

        private static void EnsureLayer()
        {
            var tagManager = new SerializedObject(AssetDatabase.LoadAllAssetsAtPath("ProjectSettings/TagManager.asset")[0]);
            var layers = tagManager.FindProperty("layers");
            var entry = layers.GetArrayElementAtIndex(LocalBodyLayer);
            if (entry.stringValue == LocalBodyLayerName) return;
            entry.stringValue = LocalBodyLayerName;
            tagManager.ApplyModifiedPropertiesWithoutUndo();
        }

        public static void BuildBetaScene()
        {
            EnsureLayer();

            var scene = EditorSceneManager.OpenScene(MapScene, OpenSceneMode.Single);

            var prefab = AssetDatabase.LoadAssetAtPath<GameObject>(PlayerPrefab);
            if (prefab == null) throw new FileNotFoundException("Player prefab missing", PlayerPrefab);

            var player = (GameObject)PrefabUtility.InstantiatePrefab(prefab, scene);
            player.name = "Player (local)";

            Transform spawn = FindSpawn();
            if (spawn != null)
                player.transform.SetPositionAndRotation(spawn.position + Vector3.up * 0.05f, spawn.rotation);

            var binder = player.GetComponent<PlayerAvatarBinder>() ?? player.AddComponent<PlayerAvatarBinder>();
            var so = new SerializedObject(binder);
            so.FindProperty("playerNick").stringValue = "cendy";
            so.ApplyModifiedPropertiesWithoutUndo();

            // The map may ship a preview camera; the player brings its own.
            foreach (var cam in UnityEngine.Object.FindObjectsByType<Camera>(FindObjectsInactive.Include))
                if (!cam.transform.IsChildOf(player.transform))
                    UnityEngine.Object.DestroyImmediate(cam.gameObject);

            Directory.CreateDirectory(Path.GetDirectoryName(BetaScene)!);
            EditorSceneManager.SaveScene(scene, BetaScene);

            EditorBuildSettings.scenes = new[]
            {
                new EditorBuildSettingsScene(BetaScene, true),
                new EditorBuildSettingsScene(ShowcaseScene, File.Exists(ShowcaseScene)),
                new EditorBuildSettingsScene(PlayerTestScene, File.Exists(PlayerTestScene)),
            };
            AssetDatabase.SaveAssets();
            Debug.Log($"[BetaSceneBuilder] Saved {BetaScene}");
        }

        private static Transform FindSpawn()
        {
            foreach (var t in UnityEngine.Object.FindObjectsByType<Transform>(FindObjectsInactive.Exclude))
                if (t.name == "SeekerSpawn") return t;
            var tagged = GameObject.FindGameObjectsWithTag(GameLayers.SpawnPointTag);
            return tagged.Length > 0 ? tagged[0].transform : null;
        }
    }
}
